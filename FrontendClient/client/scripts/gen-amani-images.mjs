/* ==========================================================================
   Generate responsive image variants for the Amani Cover pages.

   WHY THIS EXISTS
   The Amani photos shipped as ~1.5-2.4 MB PNGs, all ~1.1 megapixels. A phone
   downloaded ~27 MB of PNG before the page was usable, because <img src> has
   no width negotiation — every device got the full-size file even though a
   390px screen only ever shows ~390px of it.

   For each source image this writes WebP at 640 / 1024 / 1600 (never
   upscaling a smaller original) plus a 24px blurred LQIP, and records
   everything in src/modules/insurance/amani/imageManifest.js.

   <FillImage> reads that manifest and emits <img srcset sizes>, so the
   browser fetches exactly one appropriately-sized variant. A manifest miss
   falls back to the original URL, so this is a pure optimisation.

   The originals are KEPT on disk: they are the <picture> fallback and the
   source for a re-run.

   USAGE (from FrontendClient/client):
     npm run images:amani            # all
     npm run images:amani -- hero    # only paths containing "hero"
   Re-run whenever a photo in public/amani/ changes.
   ========================================================================== */

import sharp from 'sharp';
import { readdirSync, mkdirSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname, relative, basename, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const CLIENT = join(HERE, '..');
const SRC_DIR = join(CLIENT, 'public', 'amani');
const OUT_DIR = join(SRC_DIR, 'responsive');
const MANIFEST = join(CLIENT, 'src', 'modules', 'insurance', 'amani', 'imageManifest.js');

/* Widths a real device might ask for: 640 covers a large phone and every
   avatar, 1024 covers tablets, 1600 covers the widest desktop hero frame. */
const WIDTHS = [640, 1024, 1600];
const QUALITY = 76;

/* Small enough to inline in the manifest, big enough to read as "a photo is
   here" before the real file lands. */
const LQIP_WIDTH = 24;

const only = process.argv.slice(2);
const isTarget = (rel) => only.length === 0 || only.some((o) => rel.includes(o));

const kb = (bytes) => `${(bytes / 1024).toFixed(0)} KB`;

/* Every raster image under public/amani, skipping the responsive output we
   are about to write (otherwise a re-run would process its own work). */
function collectImages(dir, acc = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (full === OUT_DIR) continue;
      collectImages(full, acc);
      continue;
    }
    const ext = extname(entry.name).toLowerCase();
    if (ext !== '.png' && ext !== '.jpg' && ext !== '.jpeg') continue;
    acc.push({ full, rel: relative(SRC_DIR, full).split('\\').join('/') });
  }
  return acc;
}

mkdirSync(OUT_DIR, { recursive: true });

const manifest = {};
let before = 0;
let after = 0;
let converted = 0;

for (const { full, rel } of collectImages(SRC_DIR)) {
  if (!isTarget(rel)) continue;

  const sourceBytes = statSync(full).size;
  before += sourceBytes;

  const key = basename(rel, extname(rel));
  const meta = await sharp(full).metadata();

  /* Never upscale: a 500px source must not be stretched to 1024. */
  const widths = WIDTHS.filter((w) => w <= meta.width);
  if (widths.length === 0) widths.push(meta.width);

  const variants = [];
  const variantBytes = [];

  for (const width of widths) {
    /* Sizes come from sharp's own info.size (bytes it just wrote) rather than
       a second statSync — one source of truth, no half-written reads. */
    const info = await sharp(full)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: QUALITY, effort: 5 })
      .toFile(join(OUT_DIR, `${key}-${width}.webp`));
    variants.push({ width: info.width, file: `/amani/responsive/${key}-${width}.webp` });
    variantBytes.push(info.size);
    after += info.size;
  }

  const lqip = await sharp(full).resize({ width: LQIP_WIDTH }).blur(1).webp({ quality: 30 }).toBuffer();

  /* Keyed by the ORIGINAL public URL, so no call site in amaniData.js changes. */
  manifest[`/amani/${rel}`] = {
    width: meta.width,
    height: meta.height,
    variants,
    lqip: `data:image/webp;base64,${lqip.toString('base64')}`,
  };

  converted += 1;
  const optimised = kb(variantBytes[variantBytes.length - 1]);
  console.log(
    `${rel.padEnd(30)} ${String(meta.width).padStart(5)}px  ${kb(sourceBytes).padStart(7)} -> ${optimised.padStart(6)}`,
  );
}

if (converted === 0) {
  console.error('\nNo images matched — nothing written.');
  process.exit(1);
}

writeFileSync(
  MANIFEST,
  `/* AUTO-GENERATED by scripts/gen-amani-images.mjs — do not edit by hand.
   Re-run \`npm run images:amani\` after changing any photo in public/amani/.

   Maps an original image URL to responsive WebP variants plus a tiny inline
   LQIP. <FillImage> looks the URL up here; a miss falls back to the original
   file, so this is a pure optimisation with no hard dependency. */
export const IMAGE_VARIANTS = ${JSON.stringify(manifest, null, 2)};

export const OPTIMISED_IMAGE_COUNT = ${converted};
`,
);

console.log(
  `\n${converted} images optimised. ${kb(before)} -> ${kb(after)} ` +
    `(${(100 - (after / before) * 100).toFixed(1)}% smaller).`,
);
console.log(`Manifest: ${relative(CLIENT, MANIFEST)}`);
console.log('A 390px phone now downloads the 640w variant instead of the full-size PNG.');