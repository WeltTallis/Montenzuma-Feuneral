      const permitCell = row.getCell(3);
      permitCell.value = item.permit_number || '—';
      permitCell.font = { name: FONT_MONO, size: 10, color: argb(COLORS.ink), bold: true };
      permitCell.alignment = { vertical: 'middle', indent: 1 };

      // 4. Kin ID (mono, BLACK)
